const cache = new Map<BattleIcon, string>()

/** Transparent 32px PNG with white 2×2 logical pixels, ready for mask-image. */
export function battleIconUrl(id: BattleIcon): string {
  const cached = cache.get(id)
  if (cached) return cached
  const rows = MASKS[id === 'back' ? 'continue' : id]
  const pixels = new PixelBuffer(SIZE * 2, SIZE * 2)
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      if (rows[y][x] === '#') pixels.rect((id === 'back' ? SIZE - 1 - x : x) * 2, y * 2, 2, 2, [255, 255, 255])
    }
  }
  const url = pixels.toCanvas().toDataURL('image/png')
  cache.set(id, url)
  return url
}
